#!/usr/bin/env node
// Generates client/client.locale.generated.js from locale/en.json (docs/10 §11): the JSON is the
// single source of the UI copy, and the browser bundle receives it as a package-local chunk.
//
// client/module.js is a classic loader script (`window.__ModuleLoader__.load({ id, factory })`),
// not an ES module a bundler resolves, so it cannot `import` a sibling file. The host serves a
// package's client half as exactly one combo script, and serves one of its package-local chunks
// only when the file name matches the host's chunk contract (`client.<name>.js` in the bundle's own
// directory, requested as `/plugins/<pkg>/<file>?rev=…`; `packages/client-modules`). So the client
// module calls `require.async('./client.locale.generated.js')` and this file registers that chunk's
// factory under the owning package. The dictionary is never hand-copied: it is generated here and
// test/client.test.js fails when this file and locale/en.json disagree.
//
//   npm run locale:gen

import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const ROOT = new URL('..', import.meta.url)
const SOURCE = new URL('locale/en.json', ROOT)
const MANIFEST = new URL('package.json', ROOT)
const TARGET = new URL('client/client.locale.generated.js', ROOT)

/** The file name the client module requests, and the name the host's chunk route accepts. */
export const CHUNK = 'client.locale.generated.js'
/** docs/03 §9 / the repository's prettier config; the generated file must pass `prettier --check`. */
const PRINT_WIDTH = 110

/**
 * @typedef {object} LocaleFile
 * @property {{ title: string, description: string }} meta
 * @property {Record<string, string>} client
 */

/** @returns {LocaleFile} */
function readLocale() {
  return JSON.parse(readFileSync(SOURCE, 'utf8'))
}

/**
 * A JavaScript string literal in the project's prettier style: single quotes, double quotes only
 * when the text itself contains a single quote and no double quote. Nothing else is normalised, so
 * the bytes come from locale/en.json.
 *
 * @param {string} text
 * @returns {string}
 */
function quote(text) {
  const double = text.includes("'") && !text.includes('"')
  let body = text.replace(/\\/gu, '\\\\').replace(/\n/gu, '\\n').replace(/\r/gu, '\\r').replace(/\t/gu, '\\t')
  body = double ? body.replace(/"/gu, () => '\\"') : body.replace(/'/gu, () => "\\'")
  return double ? `"${body}"` : `'${body}'`
}

/**
 * The dictionary's lines, wrapped where prettier would wrap them: a property whose line would pass
 * `PRINT_WIDTH` puts its value on the next line with a two-space continuation indent.
 *
 * @param {Record<string, string>} client
 * @returns {string[]}
 */
function renderEntries(client) {
  /** @type {string[]} */
  const lines = []
  for (const [key, value] of Object.entries(client)) {
    const head = `      ${quote(key)}:`
    const line = `${head} ${quote(value)},`
    if (line.length <= PRINT_WIDTH) lines.push(line)
    else lines.push(head, `        ${quote(value)},`)
  }
  return lines
}

/**
 * The whole generated file: the loader chunk registration the host's `importChunk` executes.
 *
 * @param {string} packageName
 * @param {Record<string, string>} client
 * @returns {string}
 */
export function render(packageName, client) {
  return [
    '/* global window */',
    '// Generated by scripts/gen-locale.js from locale/en.json: run `npm run locale:gen`, never edit',
    '// this file by hand. The host serves it as a package-local chunk (the `client.` prefix and this',
    "// bundle's own directory are the host's chunk contract), so the classic client module fetches",
    '// it with require.async instead of an ES import.',
    'window.__ModuleLoader__.load({',
    `  id: ${quote(packageName)},`,
    `  chunk: ${quote(CHUNK)},`,
    '  factory: () => ({',
    '    en: {',
    ...renderEntries(client),
    '    },',
    '  }),',
    '})',
    '',
  ].join('\n')
}

const locale = readLocale()
const client = locale && locale.client
if (client === undefined || client === null || typeof client !== 'object' || Array.isArray(client)) {
  throw new TypeError('locale/en.json has no "client" section')
}
for (const [key, value] of Object.entries(client)) {
  if (typeof value !== 'string') throw new TypeError(`locale/en.json client.${key} is not a string`)
}
const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
if (typeof manifest.name !== 'string') throw new TypeError('package.json has no name')
const output = render(manifest.name, client)
const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : null
// Writing only on change keeps `npm run locale:gen` idempotent down to the file's mtime, so a
// second run cannot churn the client bundle's artifact revision and restart the page's HMR.
if (current !== output) writeFileSync(TARGET, output)
